import assert from 'node:assert/strict';
import { chromium } from 'playwright-core';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
const base = process.env.BLOG_TEST_URL || 'http://127.0.0.1:4000';
const content = JSON.parse(await readFile('.generated/blog.json', 'utf8'));
await mkdir('artifacts/rhine', { recursive: true });
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 900 }, serviceWorkers: 'block' });
await context.addInitScript(() => localStorage.setItem('rhine-settings', JSON.stringify({ sound: false, music: false, reduced: true, superPerformance: true })));
const page = await context.newPage();
const errors = [], failures = [];
page.on('pageerror', e => errors.push(e.message));
page.on('response', response => { if (response.status() >= 400 && response.url().startsWith(base)) failures.push(`${response.status()} ${response.url()}`); });
const ready = () => page.waitForFunction(() => window.rhine?.stats().ready && window.rhine.stats().startup === 'started', null, { timeout: 60000 });
const visibleDetail = () => page.locator('#detail-content').waitFor({ state: 'visible' });
try {
  await page.goto(base); await ready();
  await page.screenshot({ path: 'artifacts/rhine/desktop-archive.png' });
  // Every lane has a different size; navigate all records and wrap, using real controls.
  for (let lane = 0; lane < 5; lane++) {
    const count = Number(await page.locator('.count-total').textContent());
    assert.equal(await page.locator('#file-ticks button:visible').count(), count);
    const initial = await page.evaluate(() => window.rhine.stats().selected);
    for (let i = 0; i < count; i++) await page.locator('[data-action="next"]').click();
    assert.equal(await page.evaluate(() => window.rhine.stats().selected), initial);
    await page.locator('[data-action="column-next"]').click();
  }
  await page.locator('[data-action="search"]').click();
  await page.locator('#archive-search').fill('学校文件夹');
  assert.equal(await page.locator('.result-row').count(), 1, 'Full-text search must find body-only phrases');
  await page.locator('.result-row').click(); await visibleDetail();
  assert.equal(new URL(page.url()).pathname, '/posts/7c8a2d11/');
  assert((await page.locator('.blog-prose').textContent()).includes('先把后天的面试过好'));
  assert.equal(await page.locator('.blog-prose img').count(), 3);
  await page.screenshot({ path: 'artifacts/rhine/desktop-article.png' });
  await page.locator('[data-action="bookmark"]').click();
  assert.equal(await page.locator('[data-action="bookmark"]').getAttribute('aria-pressed'), 'true');
  await page.locator('[data-tab="notes"]').click();
  await page.locator('.blog-prose a[href="/archives/"]').click(); await visibleDetail();
  assert.equal(new URL(page.url()).pathname, '/archives/');
  await page.goBack(); await visibleDetail();
  assert.equal(new URL(page.url()).pathname, '/posts/7c8a2d11/');
  await page.reload(); await ready(); await visibleDetail();
  assert.equal(await page.locator('[data-action="bookmark"]').getAttribute('aria-pressed'), 'true');
  await page.goto(base + '/listening/?track=music'); await ready();
  await page.locator('[data-blog-play="music"]').click();
  await page.waitForFunction(() => document.querySelector('[data-player-toggle]')?.textContent === '暂停');
  assert.equal(await page.locator('.blog-player').isVisible(), true);
  await page.locator('[data-action="back"]').click();
  await page.locator('[data-action="search"]').click();
  await page.locator('#archive-search').fill('关于 Sakura'); await page.locator('.result-row').click();
  assert.equal(await page.locator('[data-player-toggle]').textContent(), '暂停', 'Music survives internal navigation');
  await page.locator('[data-player-toggle]').click();
  await page.goto(base + '/gallery/'); await ready();
  assert.equal(await page.locator('.blog-gallery img').count(), 50);
  await page.locator('.blog-tags a').first().click();
  assert.equal(new URL(page.url()).pathname, '/gallery/%E5%B0%8F%E7%BC%98/');
  assert.equal(await page.locator('.blog-gallery img').count(), 11);
  await page.goto(base + '/resources/?reader=1');
  assert.equal(await page.locator('#static-content .resource-item').count(), 10);
  assert.equal(await page.locator('[data-blog-copy]').count(), 10);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto(base + '/posts/b8e4a61c/'); await ready();
  assert.equal(await page.locator('#stage').getAttribute('data-layout'), 'portrait');
  await page.screenshot({ path: 'artifacts/rhine/mobile-article.png' });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  const pane = page.locator('#detail-content');
  assert(await pane.evaluate(el => el.scrollHeight > el.clientHeight));
  await pane.evaluate(el => { el.scrollTop = el.scrollHeight; });
  assert(await pane.evaluate(el => el.scrollTop > 0));
  const readerContext = await browser.newContext({ javaScriptEnabled: false, viewport: { width: 390, height: 844 } });
  const reader = await readerContext.newPage();
  await reader.goto(base + '/posts/b8e4a61c/');
  assert.equal(await reader.locator('#static-content').isVisible(), true);
  assert((await reader.locator('#static-content').textContent()).includes('留一盏灯'));
  await reader.screenshot({ path: 'artifacts/rhine/mobile-reader.png' });
  await readerContext.close();
  assert.deepEqual(errors, []); assert.deepEqual(failures, []);
  await writeFile('artifacts/rhine/browser-report.json', JSON.stringify({ success: true, errors, failures, routes: content.pages.length, checked: ['five variable lanes and wrap', 'full text search', 'full article and images', 'bookmark persistence', 'history and direct reload', 'music and navigation', 'gallery', 'resource codes', 'portrait scroll', 'no-JS reading'] }, null, 2));
  console.log('Browser checks passed: archive navigation, search, article, history, bookmarks, audio, gallery, resources, mobile and no-JS reading.');
} finally { await browser.close(); }
